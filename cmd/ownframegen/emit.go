package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
)

const (
	defaultGrowExtra   = 64
	estimatedExprBytes = 24
)

func needsNumBuf(nodes []Node) bool {
	for _, n := range nodes {
		switch n.Kind {
		case nodeExpr:
			if n.Raw {
				continue
			}
			switch n.FieldSpec.GoType {
			case "int", "int64", "uint64", "float64":
				return true
			}
		case nodeIf:
			if needsNumBuf(n.Then) || needsNumBuf(n.Else) {
				return true
			}
		case nodeRange:
			if needsNumBuf(n.Body) {
				return true
			}
		case nodeText:
		}
	}

	return false
}

func growExpr(nodes []Node, recv string) string {
	fixed := defaultGrowExtra
	var terms []string
	for _, n := range nodes {
		switch n.Kind {
		case nodeText:
			fixed += len(n.Text)
		case nodeExpr:
			fixed += estimatedExprBytes
		case nodeIf:
			fixed += staticByteSize(n.Then) + staticByteSize(n.Else)
		case nodeRange:
			perItem := staticByteSize(n.Body) + countExprs(n.Body)*estimatedExprBytes
			if perItem > 0 {
				terms = append(terms, fmt.Sprintf("len(%s.%s)*%d", recv, n.Field, perItem))
			}
		}
	}
	res := strconv.Itoa(fixed)
	for _, t := range terms {
		res += " + " + t
	}

	return res
}

func countExprs(nodes []Node) int {
	total := 0
	for _, n := range nodes {
		switch n.Kind {
		case nodeExpr:
			total++
		case nodeIf:
			total += countExprs(n.Then) + countExprs(n.Else)
		case nodeRange:
			total += countExprs(n.Body)
		case nodeText:
		}
	}

	return total
}

// EmitFile generates formatted Go source code for one or more parsed views.
func EmitFile(pkgName string, views []*ParsedView) ([]byte, error) {
	if !isValidIdent(pkgName) {
		return nil, fmt.Errorf("invalid Go package name %q", pkgName)
	}

	imports := collectImports(views)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by ownframegen; DO NOT EDIT.\n")
	if len(views) == 1 {
		fmt.Fprintf(&buf, "// Source: %s\n", views[0].SourceName)
	}
	buf.WriteString("\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)

	if len(imports) > 0 {
		buf.WriteString("import (\n")
		for _, imp := range imports {
			fmt.Fprintf(&buf, "\t%q\n", imp)
		}
		buf.WriteString(")\n\n")
	}

	emitConstants(&buf, views)

	for _, view := range views {
		emitView(&buf, view)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("go/format failed: %w\n--- raw source ---\n%s", err, buf.String())
	}

	return formatted, nil
}

type importFlags struct {
	context  bool
	fmtPkg   bool
	htmlPkg  bool
	strconv  bool
	ownframe bool
}

func collectImports(views []*ParsedView) []string {
	var flags importFlags
	for _, v := range views {
		if len(v.IDs) > 0 {
			flags.context = true
			flags.ownframe = true
		}
		scanNodeImports(v.Nodes, &flags)
	}

	var out []string
	if flags.context {
		out = append(out, "context")
	}
	if flags.fmtPkg {
		out = append(out, "fmt")
	}
	if flags.htmlPkg {
		out = append(out, "html")
	}
	out = append(out, "io")
	if flags.strconv {
		out = append(out, "strconv")
	}
	out = append(out, "strings")
	if flags.ownframe {
		out = append(out, "github.com/chinmay-sawant/ownframe")
	}

	return out
}

func scanNodeImports(nodes []Node, flags *importFlags) {
	for _, n := range nodes {
		switch n.Kind {
		case nodeExpr:
			if n.Raw {
				continue
			}
			switch n.FieldSpec.GoType {
			case "string":
				flags.htmlPkg = true
			case "int", "int64", "uint64", "float64", "bool":
				flags.strconv = true
			default:
				flags.fmtPkg = true
				flags.htmlPkg = true
			}
		case nodeIf:
			scanNodeImports(n.Then, flags)
			scanNodeImports(n.Else, flags)
		case nodeRange:
			scanNodeImports(n.Body, flags)
		case nodeText:
		}
	}
}

func emitConstants(buf *bytes.Buffer, views []*ParsedView) {
	seenIDConst := make(map[string]string)
	var idConsts []struct{ name, val string }
	seenActionConst := make(map[string]string)
	var actionConsts []struct{ name, val string }

	for _, v := range views {
		for _, id := range v.IDs {
			cName := "ID" + toPascalCase(id)
			if existing, ok := seenIDConst[cName]; ok {
				if existing == id {
					continue
				}
				cName = v.TypeName + cName
			}
			seenIDConst[cName] = id
			idConsts = append(idConsts, struct{ name, val string }{cName, id})
		}
		for _, act := range v.Actions {
			cName := "Action" + toPascalCase(act)
			if existing, ok := seenActionConst[cName]; ok {
				if existing == act {
					continue
				}
				cName = v.TypeName + cName
			}
			seenActionConst[cName] = act
			actionConsts = append(actionConsts, struct{ name, val string }{cName, act})
		}
	}

	if len(idConsts) > 0 {
		buf.WriteString("// Compile-time element IDs extracted from the template.\nconst (\n")
		for _, c := range idConsts {
			fmt.Fprintf(buf, "\t%s = %q\n", c.name, c.val)
		}
		buf.WriteString(")\n\n")
	}

	if len(actionConsts) > 0 {
		buf.WriteString("// Compile-time data-action names extracted from the template.\nconst (\n")
		for _, c := range actionConsts {
			fmt.Fprintf(buf, "\t%s = %q\n", c.name, c.val)
		}
		buf.WriteString(")\n\n")
	}
}

func emitView(buf *bytes.Buffer, view *ParsedView) {
	for _, s := range view.Structs {
		emitStructAndBuilders(buf, s)
	}

	// RenderTo(b *strings.Builder)
	fmt.Fprintf(buf, "// RenderTo writes the compiled HTML directly into b without reflection.\n")
	fmt.Fprintf(buf, "func (v *%s) RenderTo(b *strings.Builder) {\n", view.TypeName)
	fmt.Fprintf(buf, "\tif v == nil {\n\t\treturn\n\t}\n")
	fmt.Fprintf(buf, "\tb.Grow(%s)\n", growExpr(view.Nodes, "v"))
	if needsNumBuf(view.Nodes) {
		buf.WriteString("\tvar numBuf [32]byte\n")
	}
	emitNodes(buf, view.Nodes, "v", 0)
	buf.WriteString("}\n\n")

	// RenderString() string
	fmt.Fprintf(buf, "// RenderString renders the view into a string.\n")
	fmt.Fprintf(buf, "func (v *%s) RenderString() string {\n", view.TypeName)
	buf.WriteString("\tvar b strings.Builder\n")
	buf.WriteString("\tv.RenderTo(&b)\n")
	buf.WriteString("\treturn b.String()\n")
	buf.WriteString("}\n\n")

	// Render(w io.Writer, data any) error — matches ownframe.Config.Render!
	fmt.Fprintf(buf, "// Render implements ownframe.Config.Render without html/template reflection.\n")
	fmt.Fprintf(buf, "// If Page.SetData supplied a %s or *%s, that value is rendered; otherwise the receiver is rendered.\n", view.TypeName, view.TypeName)
	fmt.Fprintf(buf, "func (v *%s) Render(w io.Writer, data any) error {\n", view.TypeName)
	buf.WriteString("\tsrc := v\n")
	buf.WriteString("\tswitch d := data.(type) {\n")
	fmt.Fprintf(buf, "\tcase *%s:\n\t\tif d != nil {\n\t\t\tsrc = d\n\t\t}\n", view.TypeName)
	fmt.Fprintf(buf, "\tcase %s:\n\t\tsrc = &d\n", view.TypeName)
	buf.WriteString("\t}\n")
	buf.WriteString("\tif src == nil {\n\t\treturn nil\n\t}\n")
	buf.WriteString("\tif sb, ok := w.(*strings.Builder); ok {\n")
	buf.WriteString("\t\tsrc.RenderTo(sb)\n")
	buf.WriteString("\t\treturn nil\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\tvar b strings.Builder\n")
	buf.WriteString("\tsrc.RenderTo(&b)\n")
	buf.WriteString("\t_, err := io.WriteString(w, b.String())\n")
	buf.WriteString("\treturn err\n")
	buf.WriteString("}\n\n")

	if len(view.IDs) > 0 {
		emitPatchBuilder(buf, view)
	}
}

func emitStructAndBuilders(buf *bytes.Buffer, s *StructSchema) {
	fmt.Fprintf(buf, "// %s is a generated compile-time view model.\n", s.Name)
	fmt.Fprintf(buf, "type %s struct {\n", s.Name)
	for _, f := range s.Fields {
		fmt.Fprintf(buf, "\t%s %s\n", f.Name, f.GoType)
	}
	buf.WriteString("}\n\n")

	fmt.Fprintf(buf, "// New%s allocates a new %s for fluent builder chaining.\n", s.Name, s.Name)
	fmt.Fprintf(buf, "func New%s() *%s {\n", s.Name, s.Name)
	fmt.Fprintf(buf, "\treturn &%s{}\n", s.Name)
	buf.WriteString("}\n\n")

	for _, f := range s.Fields {
		if f.IsSlice && f.ItemType != nil {
			fmt.Fprintf(buf, "// With%s sets %s on the builder.\n", f.Name, f.Name)
			fmt.Fprintf(buf, "func (v *%s) With%s(items ...%s) *%s {\n", s.Name, f.Name, f.ItemType.Name, s.Name)
			fmt.Fprintf(buf, "\tv.%s = items\n", f.Name)
			buf.WriteString("\treturn v\n")
			buf.WriteString("}\n\n")

			addName := "Add" + singularize(f.Name)
			fmt.Fprintf(buf, "// %s appends one item to %s on the builder.\n", addName, f.Name)
			fmt.Fprintf(buf, "func (v *%s) %s(item %s) *%s {\n", s.Name, addName, f.ItemType.Name, s.Name)
			fmt.Fprintf(buf, "\tv.%s = append(v.%s, item)\n", f.Name, f.Name)
			buf.WriteString("\treturn v\n")
			buf.WriteString("}\n\n")
		} else {
			fmt.Fprintf(buf, "// With%s sets %s on the builder.\n", f.Name, f.Name)
			fmt.Fprintf(buf, "func (v *%s) With%s(val %s) *%s {\n", s.Name, f.Name, f.GoType, s.Name)
			fmt.Fprintf(buf, "\tv.%s = val\n", f.Name)
			buf.WriteString("\treturn v\n")
			buf.WriteString("}\n\n")
		}
	}
}

func emitNodes(buf *bytes.Buffer, nodes []Node, recv string, depth int) {
	for _, n := range nodes {
		switch n.Kind {
		case nodeText:
			fmt.Fprintf(buf, "\tb.WriteString(%s)\n", strconv.Quote(n.Text))
		case nodeExpr:
			expr := recv + "." + n.Field
			if n.Raw {
				fmt.Fprintf(buf, "\tb.WriteString(%s)\n", expr)

				continue
			}
			switch n.FieldSpec.GoType {
			case "string":
				fmt.Fprintf(buf, "\tb.WriteString(html.EscapeString(%s))\n", expr)
			case "int":
				fmt.Fprintf(buf, "\tb.Write(strconv.AppendInt(numBuf[:0], int64(%s), 10))\n", expr)
			case "int64":
				fmt.Fprintf(buf, "\tb.Write(strconv.AppendInt(numBuf[:0], %s, 10))\n", expr)
			case "uint64":
				fmt.Fprintf(buf, "\tb.Write(strconv.AppendUint(numBuf[:0], %s, 10))\n", expr)
			case "float64":
				fmt.Fprintf(buf, "\tb.Write(strconv.AppendFloat(numBuf[:0], %s, 'f', -1, 64))\n", expr)
			case "bool":
				fmt.Fprintf(buf, "\tb.WriteString(strconv.FormatBool(%s))\n", expr)
			default:
				fmt.Fprintf(buf, "\tb.WriteString(html.EscapeString(fmt.Sprint(%s)))\n", expr)
			}
		case nodeIf:
			cond := emitCondition(recv+"."+n.Field, n.FieldSpec, n.Negate)
			fmt.Fprintf(buf, "\tif %s {\n", cond)
			emitNodes(buf, n.Then, recv, depth+1)
			if len(n.Else) > 0 {
				buf.WriteString("\t} else {\n")
				emitNodes(buf, n.Else, recv, depth+1)
			}
			buf.WriteString("\t}\n")
		case nodeRange:
			iterVar := fmt.Sprintf("item%d", depth)
			fmt.Fprintf(buf, "\tfor i%d := range %s.%s {\n", depth, recv, n.Field)
			fmt.Fprintf(buf, "\t\t%s := &%s.%s[i%d]\n", iterVar, recv, n.Field, depth)
			emitNodes(buf, n.Body, iterVar, depth+1)
			buf.WriteString("\t}\n")
		}
	}
}

func emitCondition(expr string, spec *FieldSpec, negate bool) string {
	var base string
	switch {
	case spec.IsSlice:
		base = fmt.Sprintf("len(%s) > 0", expr)
	case spec.GoType == "bool":
		base = expr
	case spec.GoType == "string":
		base = expr + ` != ""`
	case spec.GoType == "int" || spec.GoType == "int64" || spec.GoType == "uint64" || spec.GoType == "float64":
		base = expr + " != 0"
	default:
		base = expr
	}

	if !negate {
		return base
	}
	switch {
	case spec.IsSlice:
		return fmt.Sprintf("len(%s) == 0", expr)
	case spec.GoType == "bool":
		return "!" + expr
	case spec.GoType == "string":
		return expr + ` == ""`
	case spec.GoType == "int" || spec.GoType == "int64" || spec.GoType == "uint64" || spec.GoType == "float64":
		return expr + " == 0"
	default:
		return "!(" + base + ")"
	}
}

func emitPatchBuilder(buf *bytes.Buffer, view *ParsedView) {
	patchType := view.TypeName + "Patch"

	fmt.Fprintf(buf, "// %s builds a typed batch of ownframe.ElementPatch edits for %s.\n", patchType, view.TypeName)
	fmt.Fprintf(buf, "type %s struct {\n", patchType)
	buf.WriteString("\tpatches []ownframe.ElementPatch\n")
	buf.WriteString("}\n\n")

	fmt.Fprintf(buf, "// Patch starts a typed fluent patch builder for %s.\n", view.TypeName)
	fmt.Fprintf(buf, "func (v *%s) Patch() *%s {\n", view.TypeName, patchType)
	fmt.Fprintf(buf, "\treturn &%s{}\n", patchType)
	buf.WriteString("}\n\n")

	fmt.Fprintf(buf, "// New%s starts a typed fluent patch builder for %s.\n", patchType, view.TypeName)
	fmt.Fprintf(buf, "func New%s() *%s {\n", patchType, patchType)
	fmt.Fprintf(buf, "\treturn &%s{}\n", patchType)
	buf.WriteString("}\n\n")

	fmt.Fprintf(buf, "func (p *%s) addEdit(id string, edit ownframe.ElementEdit) *%s {\n", patchType, patchType)
	buf.WriteString("\tfor i := range p.patches {\n")
	buf.WriteString("\t\tif p.patches[i].ID == id {\n")
	buf.WriteString("\t\t\tp.patches[i].Edits = append(p.patches[i].Edits, edit)\n")
	buf.WriteString("\t\t\treturn p\n")
	buf.WriteString("\t\t}\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\tp.patches = append(p.patches, ownframe.ElementPatch{ID: id, Edits: []ownframe.ElementEdit{edit}})\n")
	buf.WriteString("\treturn p\n")
	buf.WriteString("}\n\n")

	fmt.Fprintf(buf, "// ByID queues edits for a dynamic element ID (such as a range row).\n")
	fmt.Fprintf(buf, "func (p *%s) ByID(id string, edits ...ownframe.ElementEdit) *%s {\n", patchType, patchType)
	buf.WriteString("\tfor _, edit := range edits {\n")
	buf.WriteString("\t\tp.addEdit(id, edit)\n")
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn p\n")
	buf.WriteString("}\n\n")

	fmt.Fprintf(buf, "// Patches returns the accumulated ElementPatch slice.\n")
	fmt.Fprintf(buf, "func (p *%s) Patches() []ownframe.ElementPatch {\n", patchType)
	buf.WriteString("\treturn p.patches\n")
	buf.WriteString("}\n\n")

	fmt.Fprintf(buf, "// Len returns the number of distinct elements queued for patching.\n")
	fmt.Fprintf(buf, "func (p *%s) Len() int {\n", patchType)
	buf.WriteString("\treturn len(p.patches)\n")
	buf.WriteString("}\n\n")

	fmt.Fprintf(buf, "// Apply commits every queued edit to page in one PatchElements call.\n")
	fmt.Fprintf(buf, "func (p *%s) Apply(ctx context.Context, page *ownframe.Page) error {\n", patchType)
	buf.WriteString("\tif len(p.patches) == 0 {\n\t\treturn nil\n\t}\n")
	buf.WriteString("\treturn page.PatchElements(ctx, p.patches)\n")
	buf.WriteString("}\n\n")

	for _, id := range view.IDs {
		prefix := toPascalCase(id)
		fmt.Fprintf(buf, "// %sText replaces the text content of #%s.\n", prefix, id)
		fmt.Fprintf(buf, "func (p *%s) %sText(text string) *%s {\n", patchType, prefix, patchType)
		fmt.Fprintf(buf, "\treturn p.addEdit(%q, ownframe.ElementEdit{Text: &text})\n", id)
		buf.WriteString("}\n\n")

		fmt.Fprintf(buf, "// %sAddClass adds className to #%s.\n", prefix, id)
		fmt.Fprintf(buf, "func (p *%s) %sAddClass(className string) *%s {\n", patchType, prefix, patchType)
		fmt.Fprintf(buf, "\treturn p.addEdit(%q, ownframe.ElementEdit{AddClass: className})\n", id)
		buf.WriteString("}\n\n")

		fmt.Fprintf(buf, "// %sRemoveClass removes className from #%s.\n", prefix, id)
		fmt.Fprintf(buf, "func (p *%s) %sRemoveClass(className string) *%s {\n", patchType, prefix, patchType)
		fmt.Fprintf(buf, "\treturn p.addEdit(%q, ownframe.ElementEdit{RemoveClass: className})\n", id)
		buf.WriteString("}\n\n")

		fmt.Fprintf(buf, "// %sToggleClass toggles className on #%s.\n", prefix, id)
		fmt.Fprintf(buf, "func (p *%s) %sToggleClass(className string) *%s {\n", patchType, prefix, patchType)
		fmt.Fprintf(buf, "\treturn p.addEdit(%q, ownframe.ElementEdit{ToggleClass: className})\n", id)
		buf.WriteString("}\n\n")

		fmt.Fprintf(buf, "// %sSetAttr sets attribute name=value on #%s.\n", prefix, id)
		fmt.Fprintf(buf, "func (p *%s) %sSetAttr(name, value string) *%s {\n", patchType, prefix, patchType)
		fmt.Fprintf(buf, "\treturn p.addEdit(%q, ownframe.ElementEdit{Attribute: name, Value: value})\n", id)
		buf.WriteString("}\n\n")

		fmt.Fprintf(buf, "// %sRemoveAttr removes attribute name from #%s.\n", prefix, id)
		fmt.Fprintf(buf, "func (p *%s) %sRemoveAttr(name string) *%s {\n", patchType, prefix, patchType)
		fmt.Fprintf(buf, "\treturn p.addEdit(%q, ownframe.ElementEdit{RemoveAttribute: name})\n", id)
		buf.WriteString("}\n\n")

		fmt.Fprintf(buf, "// %sInnerHTML replaces the child HTML of #%s.\n", prefix, id)
		fmt.Fprintf(buf, "func (p *%s) %sInnerHTML(fragment string) *%s {\n", patchType, prefix, patchType)
		fmt.Fprintf(buf, "\treturn p.addEdit(%q, ownframe.ElementEdit{InnerHTML: &fragment})\n", id)
		buf.WriteString("}\n\n")

		fmt.Fprintf(buf, "// %sAppendHTML appends an HTML fragment inside #%s.\n", prefix, id)
		fmt.Fprintf(buf, "func (p *%s) %sAppendHTML(fragment string) *%s {\n", patchType, prefix, patchType)
		fmt.Fprintf(buf, "\treturn p.addEdit(%q, ownframe.ElementEdit{AppendHTML: fragment})\n", id)
		buf.WriteString("}\n\n")

		fmt.Fprintf(buf, "// %sRemoveChild removes descendant childID from #%s.\n", prefix, id)
		fmt.Fprintf(buf, "func (p *%s) %sRemoveChild(childID string) *%s {\n", patchType, prefix, patchType)
		fmt.Fprintf(buf, "\treturn p.addEdit(%q, ownframe.ElementEdit{ID: childID, Remove: true})\n", id)
		buf.WriteString("}\n\n")
	}
}
